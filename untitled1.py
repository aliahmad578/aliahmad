import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.model_selection import train_test_split
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import accuracy_score, classification_report

# 1. Create a synthetic healthcare dataset for demonstration
np.random.seed(42)
n_samples = 500

data = {
    'Patient_ID': range(1, n_samples + 1),
    'Age': np.random.randint(18, 90, size=n_samples),
    'Blood_Pressure': np.random.randint(90, 180, size=n_samples),
    'Cholesterol': np.random.randint(150, 300, size=n_samples),
    'Outcome': np.random.choice(['Healthy', 'At Risk', 'Critical'], size=n_samples, p=[0.5, 0.3, 0.2])
}

df = pd.DataFrame(data)
print("--- Dataset Preview ---")
print(df.head())
print("\n--- Dataset Information ---")
print(df.info())

# 2. Perform EDA & Draw Pie Graph
print("\n--- EDA: Class Distribution (Pie Graph) ---")
class_counts = df['Outcome'].value_counts()

plt.figure(figsize=(6, 6))
plt.pie(class_counts, labels=class_counts.index, autopct='%1.1f%%', colors=['#4CAF50', '#FFC107', '#F44336'], startangle=140)
plt.title('Distribution of Health Outcomes')
plt.show()

# 3. Split the data with an 80:20 ratio
X = df[['Age', 'Blood_Pressure', 'Cholesterol']]
y = df['Outcome']

X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.20, random_state=42, stratify=y)
print(f"Data successfully split: Train set size = {X_train.shape[0]}, Test set size = {X_test.shape[0]}")

# 4. Train the Model & Test the Data
clf = RandomForestClassifier(random_state=42)
clf.fit(X_train, y_train)

y_pred = clf.predict(X_test)

# 5. Find Accuracy and Classify Reports
accuracy = accuracy_score(y_test, y_pred)
print(f"\nAccuracy: {accuracy:.4f} ({accuracy * 100:.2f}%)")

print("\nClassification Report:")
print(classification_report(y_test, y_pred))

# 6. Predict Actual Data with Labelled Data
results_df = pd.DataFrame({
    'Actual_Label': y_test,
    'Predicted_Label': y_pred
})
print("\n--- Actual vs Predicted Labels (First 10 Samples) ---")
print(results_df.head(10))

import pickle

# Save the model to a file
model_filename = 'healthcare_classifier_model.pkl'
with open(model_filename, 'wb') as file:
    pickle.dump(clf, file)

print(f"Model successfully saved as {model_filename}")